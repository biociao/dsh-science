#!/usr/bin/env node
// DSH 0.2 registers presets through bundle declarations, not directory scanning.
// Keep the editable agent entry lists as the source; preserve !!js expressions.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
for (const [dir, id, name, order] of [
  ['preset', 'science', '科学模式', 20],
  ['preset-biomni', 'biomni', 'Biomni 模式', 21],
]) {
  const source = await readFile(path.join(root, dir, 'agent.cordis.yml'), 'utf8');
  const metadata = await readFile(path.join(root, dir, 'preset.yml'), 'utf8');
  const description = metadata.split('\n').find(line => line.startsWith('description:'))?.slice('description:'.length).trim();
  if (!description) throw new Error(`${dir}/preset.yml is missing its description`);
  const entries = source.replace(/name: (['"]?)\.\/engines\//g, 'name: $1dsh-science/engines/');
  const output = `# Generated by scripts/build-preset-bundles.mjs; edit agent.cordis.yml instead.\n- insert:\n    - id: preset-${id}\n      name: '@deepseek-ai/dsh-agent-preset'\n      config:\n        id: ${id}\n        name: ${name}\n        description: ${description}\n        order: ${order}\n        plugins:\n${entries.trimEnd().split('\n').map(line => line ? `          ${line}` : '').join('\n')}\n`;
  const file = path.join(root, dir, 'cordis.patch.yml');
  if (check) {
    if (await readFile(file, 'utf8').catch(() => '') !== output) {
      throw new Error(`${dir}/cordis.patch.yml is stale; run npm run build:presets`);
    }
  } else {
    await writeFile(file, output);
  }
  console.log(`${check ? 'Checked' : 'Built'} ${dir}/cordis.patch.yml`);
}
